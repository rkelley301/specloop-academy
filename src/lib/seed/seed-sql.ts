import type { Lesson, LearningPath } from "../types";

// Generates supabase/migrations/0003_seed_ccst_l1.sql from the same seed data
// the app bundles, so database question ids always match the app's.

function q(v: string | number | boolean | null): string {
  if (v === null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

export function seedSql(path: LearningPath, lessons: Lesson[], seedVersion: string): string {
  const out: string[] = [
    `-- GENERATED by \`npm run seed:sql\` from the bundled seed course (${seedVersion}). Do not edit by hand.`,
    "-- Shared, read-only seed content (owner_id null). Re-running replaces it in place.",
    "",
    "begin;",
    "",
    `insert into public.learning_paths (id, owner_id, title, description, origin) values (${q(path.id)}, null, ${q(path.title)}, ${q(path.description)}, 'seed')`,
    "  on conflict (id) do update set title = excluded.title, description = excluded.description;",
    "",
  ];
  for (const l of lessons) {
    out.push(`-- ${l.id}: ${l.title}`);
    out.push(
      `insert into public.lessons (id, owner_id, path_id, position, title, objective, est_minutes, script, script_version, source_note, review_status, origin) values (${[
        q(l.id), "null", q(l.pathId), q(l.order), q(l.title), q(l.objective), q(l.estMinutes), q(l.script), q(l.scriptVersion), q(l.sourceNote), q(l.reviewStatus), "'seed'",
      ].join(", ")})`,
      "  on conflict (id) do update set position = excluded.position, title = excluded.title, objective = excluded.objective, est_minutes = excluded.est_minutes, script = excluded.script, script_version = excluded.script_version, source_note = excluded.source_note, review_status = excluded.review_status;",
    );
    for (const v of l.scriptHistory) {
      out.push(
        `insert into public.lesson_script_versions (lesson_id, version, script, saved_at) values (${q(l.id)}, ${q(v.version)}, ${q(v.script)}, ${q(v.savedAt)}) on conflict (lesson_id, version) do update set script = excluded.script;`,
      );
    }
    for (const c of l.concepts) {
      out.push(`insert into public.concepts (id, lesson_id, label) values (${q(c.id)}, ${q(l.id)}, ${q(c.label)}) on conflict (id) do update set label = excluded.label;`);
    }
    const qs = [
      ...l.questions.map((x, i) => ({ ...x, kind: "recall", position: i + 1, missing: false })),
      { ...l.scenario, kind: "scenario", position: l.questions.length + 1, missing: Boolean(l.scenario.answerKeyMissing) },
    ];
    for (const x of qs) {
      out.push(
        `insert into public.questions (id, lesson_id, concept_id, kind, position, prompt, answer_key, answer_key_missing) values (${[
          q(x.id), q(l.id), q(x.conceptId), q(x.kind), q(x.position), q(x.prompt), q(x.answerKey), q(x.missing),
        ].join(", ")}) on conflict (id) do update set prompt = excluded.prompt, answer_key = excluded.answer_key, answer_key_missing = excluded.answer_key_missing, position = excluded.position;`,
      );
    }
    out.push(`delete from public.lesson_attributions where lesson_id = ${q(l.id)} and draft_id is null;`);
    for (const a of l.sources) {
      out.push(
        `insert into public.lesson_attributions (lesson_id, title, citation, url) values (${q(l.id)}, ${q(a.title)}, ${q(a.citation)}, ${q(a.url ?? null)});`,
      );
    }
    out.push("");
  }
  out.push("commit;", "");
  return out.join("\n");
}
